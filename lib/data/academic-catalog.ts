export function getDefaultSanityCourseBySlug(slug: string): SanityCourse | null {
  const item = DEFAULT_ACADEMIC_CATALOG.find((c) => c.slug === slug || c.id === slug)
  if (!item) return null

  return {
    _id: item.id,
    _type: "course",
    _createdAt: "2025-01-01T00:00:00Z",
    _updatedAt: "2025-01-01T00:00:00Z",
    title: item.title,
    slug: {
      _type: "slug",
      current: item.slug,
    },
    heroImage: item.heroImage,
    offeringCategory: item.category,
    degreeType: item.degreeType,
    credential: item.credential,
    badge: item.badge,
    featured: item.featured,
    majors: item.majors,
    deliveryMode: (item.deliveryMode?.toLowerCase().includes("campus") ? "on-campus" : "hybrid") as any,
    duration: item.duration,
    level: (item.category === "ched" ? "undergrad" : item.category === "tesda" ? "tvet" : "undergrad") as any,
    summary: item.summary,
    description: item.description,
    highlights: item.highlights,
    learningOutcomes: item.learningOutcomes,
    curriculumStructure: item.curriculumStructure,
    careerPaths: item.careerPaths,
    targetAudience: item.targetAudience,
    outcomes: item.outcomes,
    creditHours: item.creditHours,
    trainingHours: item.trainingHours,
    tuition: item.tuition,
    financialAidHighlight: item.financialAidHighlight,
    scholarshipsAvailable: item.scholarshipsAvailable,
    intakeSchedule: item.intakeSchedule,
    admissionsRequirements: item.admissionsRequirements,
    applicationDeadlines: item.applicationDeadlines,
    status: "active",
    cta: item.cta,
    relatedOfferings: (item.relatedSlugs || []).map((rSlug) => {
      const related = DEFAULT_ACADEMIC_CATALOG.find((r) => r.slug === rSlug)
      return {
        _id: rSlug,
        title: related?.title || rSlug,
        slug: { current: rSlug },
      }
    }),
    seo: {
      metaTitle: `${item.title} | Data Center College Baguio`,
      metaDescription: item.summary,
      shareImage: item.heroImage,
    },
  }
}

